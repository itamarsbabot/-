export function allTopics(subject) {
  return SYLLABUS[subject].units.flatMap((u) => u.topics.map((t) => ({ ...t, grade: u.grade, unit: u.title })));
}

// Short text version of the syllabus for the tutor's instructions.
export function syllabusText(subject, focus = null) {
  const s = SYLLABUS[subject] || SYLLABUS.math;
  const lines = [];
  for (const u of s.units) {
    lines.push(`כיתה ${u.grade} – ${u.title}:`);
    for (const t of u.topics) lines.push(`- ${t.name}: ${t.subs.join("; ")}`);
  }
  let out = `סילבוס ${s.full}:\n${lines.join("\n")}`;
  if (focus?.length) out += `\n\nנושאים שליה כבר למדה או לומדת עכשיו: ${focus.join(", ")}.\nבתרגולים ובמבחנים אל תשתמשי בחומר שעוד לא נלמד, אלא אם התבקשת במפורש.`;
  return out;
}
