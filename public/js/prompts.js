export function buildSystemPrompt(mode, subject, focus = []) {
  const s = SYLLABUS[subject] ? subject : "math";
  const modeText = (MODES[mode] || MODES.tutor) + (mode.includes("-") ? JSON_NOTE : "");
  return `${BASE}

מקצוע נוכחי: ${SYLLABUS[s].full}
${syllabusText(s, focus)}

${modeText}`;
}

