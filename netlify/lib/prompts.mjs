const JSON_NOTE = `
חשוב לגבי JSON: בתוך מחרוזות JSON יש להכפיל כל לוכסן הפוך של LaTeX (למשל "\\\\frac{1}{2}" ולא "\\frac{1}{2}"), ולכתוב ירידת שורה כ-\\n.`;

export function buildSystemPrompt(mode, subject) {
  const cur = CURRICULUM[subject] || CURRICULUM.math;
  const topics = cur.topics.map((t) => `- ${t}`).join("\n");
  const modeText = (MODES[mode] || MODES.tutor) + (mode.includes("-") ? JSON_NOTE : "");
  return `${BASE}

מקצוע נוכחי: ${cur.name}
נושאי הלימוד:
${topics}

${modeText}`;
}
